def _form_labels(labels):
    return {
        f"{{{{ form.{field}.label }}}}": f'{{{{ form.{field}.label(text="{label}") }}}}'
        for field, label in labels.items()
    }


def _form_descriptions(descriptions):
    return {f"{{{{ form.{field}.description }}}}": description for field, description in descriptions.items()}


def _choices(expression, labels):
    # Localize only option text in WTForms output, preserving option values.
    filters = "".join(f' | replace(">{label}<"|safe, ">{translation}<"|safe)' for label, translation in labels.items())
    return f"{{{{ {expression}{filters} }}}}"


